#!/bin/bash
# test-flushfail.sh — WP22c e2e: the two durability bugs the dm-flakey
# tier found (tools/flakey/FINDINGS.md), reproduced deterministically on
# plain image files (no root/dm needed), plus the fsck/verify agreement
# invariant. Persistent regression suite.
#
#   Leg A (F1): the INVFS_SYNC_FAIL_AT hook simulates the leg-2 error
#   window: the Nth vol_sync of the process zeroes the un-barriered
#   inode-area tail (what a dropped writeback leaves behind) and reports
#   EIO. Asserts: the failure is LOUD at the failing sync, the volume
#   latches (later mutations refused), the append cursor is re-anchored
#   at the last barriered position, and after a clean close + reopen the
#   barriered file is present and bit-exact while the un-barriered one is
#   absent on v2 (complete-or-absent, never silently lost after an ack).
#   WP80: v3 is the only format mkfs writes now. Its delta append is
#   itself barriered (see docs/architecture/META.md), so the second
#   create is durable BEFORE the failing sync; the failure still latches
#   and refuses later mutations, and the file comes back bit-exact
#   (complete-or-absent, here: complete).
#
#   Leg B (F2 rename): a fast-path rename must kill the SOURCE name's own
#   record (the pre-fix tombstone named the shared id's newest record --
#   the copy -- and killed nothing at replay, leaving both names live).
#   Asserts in-session and post-reopen: source absent, target bit-exact.
#
#   Leg C (F2 shared-id retire): deleting one name of a hardlinked pair
#   must not drop the mappings the survivor resolves through (the old
#   retire dropped the shared id's L2P wholesale -> present-but-
#   unreadable). Asserts the survivor reads bit-exact in-session and
#   after reopen, fsck + verify clean.
#
#   Leg D (F2 fsck honesty): a live record whose mappings are gone (built
#   offline: hardlinked survivor + legacy tombstone + zeroed journal
#   tail -- the leg-5 artifact's shape) must be SEEN by fsck: l2p_miss
#   counted, the file named, rc=3 -- and verify --deep must say CORRUPT
#   for the same file. Pre-fix fsck reported OK with 0 misses.
#
#   Leg E (F2 container rename): renaming a swept container file (TARR:
#   num_children==0 but payload in "name!partN"/"name!recipe" siblings)
#   must take the sibling-aware slow path, not the hardlink fast path --
#   the hardlink would move the anchor and strand the recipe under the
#   old name (the renamed container never reads again). Asserts the
#   renamed container reads bit-exact in-session and after reopen.
#
# The engine harness is generated below and linked against the built
# engine objects (the test-astv2.sh convention). Run from the repo root
# after `make`. Uses /dev/shm like the other soak scripts; image paths
# are RELATIVE (blkio treats /dev/* as raw devices).
set -e
set -o pipefail

REPO="${REPO:-$(cd "$(dirname "$0")/.." && pwd)}"   # override with the worktree when testing a branch
B=$REPO/bin
WORK=/dev/shm/wp22c
IMG_A=wp22c-a.img     # leg A: sync failure latch + re-anchor
IMG_B=wp22c-b.img     # leg B: rename kills the source name
IMG_C=wp22c-c.img     # leg C: shared-id retire keeps the survivor readable
IMG_D=wp22c-d.img     # leg D: fsck/verify agree on a dangling live record
IMG_E=wp22c-e.img     # leg E: swept-container rename moves the siblings
rm -rf "$WORK" && mkdir -p "$WORK"
cd /dev/shm
rm -f "$IMG_A" "$IMG_B" "$IMG_C" "$IMG_D" "$IMG_E"

fail() { echo "FAIL: $*" >&2; exit 1; }

# WP80: on-disk format probe (format_version byte at 0x90; 0 = v0 generation).
img_is_meta() {
    python3 - "$1" <<'PY'
import sys
try:
    with open(sys.argv[1], "rb") as f:
        sb = f.read(0x91)
except OSError:
    sys.exit(1)
sys.exit(0 if len(sb) >= 0x91 and sb[0x90] == 0 else 1)
PY
}

