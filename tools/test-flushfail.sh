/* ff_harness.c — WP22c engine-level test driver (generated by
 * tools/test-flushfail.sh; links the engine objects, public API + the
 * on-disk structs for the offline sabotage leg). */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>
#include <stddef.h>
#include "volume.h"
