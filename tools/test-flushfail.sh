static void die(const char *m) { fprintf(stderr, "HARNESS-FAIL: %s\n", m); exit(1); }

static void fill_pattern(uint8_t *b, size_t n, uint64_t seed)
{
    uint64_t x = seed ? seed : 0x9E3779B97F4A7C15ull;
    size_t i;
    for (i = 0; i < n; i++) {
        x ^= x << 13; x ^= x >> 7; x ^= x << 17;
        b[i] = (uint8_t)(x >> 32);
    }
}

static void assert_file(invfs_volume *v, const char *name, size_t len,
                        uint64_t seed)
{
    uint64_t id = vol_find(v, name);
    uint8_t *buf = NULL, *want;
    size_t blen = 0;
    if (!id) die("assert_file: absent");
    if (vol_read_file(v, id, &buf, &blen) != 0) die("assert_file: read");
    if (blen != len) die("assert_file: size");
    want = malloc(len);
    if (!want) die("oom");
    fill_pattern(want, len, seed);
    if (memcmp(want, buf, len) != 0) die("assert_file: content mismatch");
    free(want);
    free(buf);
}

static uint64_t create_pattern(invfs_volume *v, const char *name,
                               size_t len, uint64_t seed)
{
    uint8_t *buf = malloc(len);
    uint64_t id;
    if (!buf) die("oom");
    fill_pattern(buf, len, seed);
    id = vol_create_file(v, name, buf, len);
    free(buf);
    if (!id) die("create_pattern");
    return id;
}

/* ---- leg A: failed barrier -> latch + re-anchor ----------------------- */
static int cmd_f1run(const char *img)
{
    int err = 0;
    invfs_volume *v = vol_open(img, &err);
    uint64_t anchor;
    if (!v) die("open");
    /* pinned file: committed and barriered on the healthy device */
    create_pattern(v, "pin1.bin", 100 * 1024, 11);
    if (vol_sync(v) != 0) die("first sync failed on a healthy image");
    anchor = vol_inode_area_pos(v);
    /* the un-barriered file: committed, then the storm hits at the sync */
    create_pattern(v, "hole1.bin", 200 * 1024, 22);
    if (vol_sync(v) == 0)
        die("second sync succeeded despite INVFS_SYNC_FAIL_AT");
    /* loud at the failing op; latched from here on */
    if (vol_write_enabled(v))
        die("volume not latched after a failed sync");
    /* the append cursor must never sit past unpersisted bytes */
    if (vol_inode_area_pos(v) != anchor)
        die("append cursor not re-anchored at the last barrier");
    /* later mutations fail loudly instead of appending into the hole */
    if (vol_create_file(v, "post.bin", (const uint8_t *)"x", 1) != 0)
        die("create accepted on a latched volume");
    vol_close(v);
    printf("F1RUN-OK\n");
    return 0;
}

static int cmd_f1check(const char *img)
{
    int err = 0;
    invfs_volume *v = vol_open(img, &err);
    if (!v) die("open");
    assert_file(v, "pin1.bin", 100 * 1024, 11);
    if (vol_find(v, "hole1.bin")) die("hole1.bin survived a failed sync");
    if (vol_find(v, "post.bin"))  die("post.bin exists");
    vol_close(v);
    printf("F1CHECK-OK\n");
    return 0;
}

/* ---- leg B: a fast-path rename retires the source's own record -------- */
static int cmd_f2rename(const char *img)
{
    int err = 0;
    invfs_volume *v = vol_open(img, &err);
    if (!v) die("open");
    create_pattern(v, "fileA.bin", 300 * 1024, 33);
    if (vol_rename(v, "fileA.bin", "fileB.bin") != 0) die("rename");
    /* in-session: the source name must be gone immediately */
    if (vol_find(v, "fileA.bin")) die("source name survived the rename");
    if (!vol_find(v, "fileB.bin")) die("target name missing after rename");
    vol_close(v);
    /* and the same after a full reopen (the on-disk tombstone must hit) */
    v = vol_open(img, &err);
    if (!v) die("reopen");
    if (vol_find(v, "fileA.bin")) die("source name resurrected at reopen");
    assert_file(v, "fileB.bin", 300 * 1024, 33);
    vol_close(v);
    printf("F2RENAME-OK\n");
    return 0;
}

/* ---- leg C: a shared-id retire must keep the survivor's mappings ------ */
static int cmd_f2link(const char *img)
{
    int err = 0;
    invfs_volume *v = vol_open(img, &err);
    if (!v) die("open");
    create_pattern(v, "fileC.bin", 160 * 1024, 44);
    if (vol_hardlink(v, "fileC.bin", "linkC.bin") != 0) die("hardlink");
    if (vol_delete_file(v, "fileC.bin") != 0) die("delete");
    assert_file(v, "linkC.bin", 160 * 1024, 44);   /* in-session */
    vol_close(v);
    v = vol_open(img, &err);
    if (!v) die("reopen");
    if (vol_find(v, "fileC.bin")) die("deleted name still present");
    assert_file(v, "linkC.bin", 160 * 1024, 44);   /* after replay */
    vol_close(v);
    printf("F2LINK-OK\n");
    return 0;
}

/* ---- leg D: build the dangling live record (the leg-5 shape) ---------- */
static int cmd_f2mkdangle(const char *img)
{
    int err = 0;
    invfs_volume *v = vol_open(img, &err);
    uint64_t vid;
    if (!v) die("open");
    /* bystander FIRST: the victim's mappings must be the journal tail */
    create_pattern(v, "bystanderB.bin", 32 * 1024, 55);
    vid = create_pattern(v, "victimV.bin", 160 * 1024, 66);
    /* the survivor shares the victim's id (the rename fast path's shape) */
    if (vol_hardlink(v, "victimV.bin", "survivorS.bin") != 0)
        die("hardlink");
    vol_close(v);
    printf("F2MKDANGLE-OK victim_id=%llu\n", (unsigned long long)vid);
    return 0;
}

/* the drop-window analogue (WP22d: the on-disk journal is no longer
 * rewriteable test collateral, so the maps are dropped through the
 * engine): the victim's name is deleted (the shared-id guard keeps the
 * maps), then the shared id's mappings are UNMAP-journaled away. The
 * survivor's record stays live with no mappings -- exactly what the
 * leg-5 artifact held. */
static int cmd_f2sabotage(const char *img, uint64_t victim_id)
{
    int err = 0;
    invfs_volume *v = vol_open(img, &err);
    const invfs_l2p_entry *t;
    size_t n = 0, i, nl = 0;
    uint64_t *lbas;
    if (!v) die("open");
    if (vol_delete_file(v, "victimV.bin") != 0) die("delete victim");
    t = vol_l2p(v, &n);
    lbas = malloc(n * sizeof *lbas);
    if (!lbas) die("oom");
    for (i = 0; i < n; i++)
        if (t[i].type == INVFS_JRN_MAP && t[i].inode == victim_id)
            lbas[nl++] = t[i].lba;
    if (!nl) die("no victim mappings found");
    for (i = 0; i < nl; i++)
        vol_l2p_remove(v, victim_id, lbas[i]);
    free(lbas);
    if (vol_flush(v) != 0) die("flush");
    vol_close(v);
    printf("F2SABOTAGE-OK\n");
    return 0;
}

/* ---- leg G: a compaction crash at each stage is consistent-cut -------- */
static int cmd_f3fill(const char *img)
{
    int err = 0;
    invfs_volume *v = vol_open(img, &err);
    if (!v) die("open");
    /* the pinned file: committed and barriered BEFORE the crash run */
    create_pattern(v, "pinA.bin", 96 * 1024, 77);
    if (vol_sync(v) != 0) die("sync");
    vol_close(v);
    printf("F3FILL-OK\n");
    return 0;
}

/* with INVFS_JRN_FORCE_COMPACT=1 + INVFS_COMPACT_ABORT_AT set, the create
 * below dies SIGKILL mid-compaction (in its pre_record flush) */
static int cmd_f3crash(const char *img)
{
    int err = 0;
    invfs_volume *v = vol_open(img, &err);
    if (!v) die("open");
    create_pattern(v, "newB.bin", 128 * 1024, 88);
    vol_close(v);
    printf("F3CRASH-survived\n");   /* reached only when the hook is off */
    return 0;
}

static int cmd_f3check(const char *img)
{
    int err = 0;
    invfs_volume *v = vol_open(img, &err);
    if (!v) die("open");
    /* the pinned file must be intact; the crashed one is present-and-
     * bit-exact or absent (complete-or-absent) -- never torn */
    assert_file(v, "pinA.bin", 96 * 1024, 77);
    if (vol_find(v, "newB.bin"))
        assert_file(v, "newB.bin", 128 * 1024, 88);
    vol_close(v);
    printf("F3CHECK-OK\n");
    return 0;
}

/* leg G2 variant: the pinned file came from the OLD (flat-log) binaries,
 * so only the crashed create's complete-or-absent is checked here; the
 * pinned file's bit-exactness is asserted by the leg via invf-cat | cmp */
static int cmd_f3checkb(const char *img)
{
    int err = 0;
    invfs_volume *v = vol_open(img, &err);
    if (!v) die("open");
    if (vol_find(v, "newB.bin"))
        assert_file(v, "newB.bin", 128 * 1024, 88);
    vol_close(v);
    printf("F3CHECKB-OK\n");
    return 0;
}

/* ---- leg I: bitmap/journal divergence (WP22d open-time reconcile) ---- */
/* create the survivor, sync, and print the pba of its first segment (the
 * leg then clears that bit in the on-disk bitmap, simulating a bitmap
 * page dropped by a window while the journal append landed) */
static int cmd_f4mkdiv(const char *img)
{
    int err = 0;
    invfs_volume *v = vol_open(img, &err);
    uint64_t id, pba = 0, len;
    size_t n = 0, i;
    const invfs_l2p_entry *t;
    if (!v) die("open");
    id = create_pattern(v, "survivorS.bin", 192 * 1024, 55);
    if (vol_sync(v) != 0) die("sync");
    t = vol_l2p(v, &n);
    for (i = 0; i < n; i++)
        if (t[i].type == INVFS_JRN_MAP && t[i].inode == id) {
            pba = t[i].pba; break;
        }
    if (!pba) die("no mapping for the survivor");
    printf("F4MKDIV-OK pba=%llu\n", (unsigned long long)pba);
    vol_close(v);
    return 0;
}

/* after the sabotage: the open must reconcile (the survivor's block is
 * forced used), then a fresh write must NOT be allocated on it */
static int cmd_f4checkdiv(const char *img)
{
    int err = 0;
    invfs_volume *v = vol_open(img, &err);
    if (!v) die("open");
    assert_file(v, "survivorS.bin", 192 * 1024, 55);
    create_pattern(v, "attackerA.bin", 256 * 1024, 66);
    if (vol_sync(v) != 0) die("sync");
    assert_file(v, "survivorS.bin", 192 * 1024, 55);
    assert_file(v, "attackerA.bin", 256 * 1024, 66);
    vol_close(v);
    printf("F4CHECKDIV-OK\n");
    return 0;
}

/* ---- leg E: renaming a swept container keeps its siblings ----------- */
static int cmd_f2cp(const char *img, const char *host, const char *name)
{
    int err = 0;
    invfs_volume *v = vol_open(img, &err);
    FILE *f;
    long len;
    uint8_t *buf;
    uint64_t id;
    if (!v) die("open");
    f = fopen(host, "rb");
    if (!f) die("host fopen");
    if (fseek(f, 0, SEEK_END) != 0 || (len = ftell(f)) < 0 ||
        fseek(f, 0, SEEK_SET) != 0) die("host size");
    buf = malloc((size_t)len);
    if (!buf) die("oom");
    if (fread(buf, 1, (size_t)len, f) != (size_t)len) die("host read");
    fclose(f);
    id = vol_create_file(v, name, buf, (size_t)len);
    free(buf);
    if (!id) die("create");
    vol_close(v);
    printf("F2CP-OK\n");
    return 0;
}

/* rename must REFUSE (-4) while a sweep checkpoint is live: a rollback
 * would tear the pair (the copy decapitated, the source resurrected) */
static int cmd_f2mvrefuse(const char *img, const char *name,
                          const char *newname)
{
    int err = 0;
    invfs_volume *v = vol_open(img, &err);
    int rc;
    if (!v) die("open");
    rc = vol_rename(v, name, newname);
    if (rc != -4) die("rename under a live checkpoint not refused");
    if (!vol_find(v, name)) die("source gone after a refused rename");
    if (vol_find(v, newname)) die("target appeared after a refused rename");
    vol_close(v);
    printf("F2MVREFUSE-OK\n");
    return 0;
}

/* rename name->newname, then bit-compare newname against the host file,
 * in-session and after a full reopen */
static int cmd_f2mv(const char *img, const char *name, const char *newname,
                    const char *host)
{
    int err = 0;
    invfs_volume *v = vol_open(img, &err);
    FILE *f;
    long len;
    uint8_t *want, *got = NULL;
    size_t glen = 0;
    uint64_t id;
    int rc = 1;
    if (!v) die("open");
    f = fopen(host, "rb");
    if (!f) die("host fopen");
    if (fseek(f, 0, SEEK_END) != 0 || (len = ftell(f)) < 0 ||
        fseek(f, 0, SEEK_SET) != 0) die("host size");
    want = malloc((size_t)len);
    if (!want) die("oom");
    if (fread(want, 1, (size_t)len, f) != (size_t)len) die("host read");
    fclose(f);
    if (vol_rename(v, name, newname) != 0) die("rename");
    if (vol_find(v, name)) die("container source name survived the rename");
    id = vol_find(v, newname);
    if (!id) die("renamed container missing");
    if (vol_read_file(v, id, &got, &glen) != 0)
        die("renamed container unreadable in-session");
    if (glen != (size_t)len || memcmp(want, got, glen) != 0)
        die("renamed container content mismatch in-session");
    free(got); got = NULL;
    vol_close(v);
    v = vol_open(img, &err);
    if (!v) die("reopen");
    if (vol_find(v, name)) die("container source resurrected at reopen");
    id = vol_find(v, newname);
    if (!id) die("renamed container missing after reopen");
    if (vol_read_file(v, id, &got, &glen) != 0)
        die("renamed container unreadable after reopen");
    if (glen != (size_t)len || memcmp(want, got, glen) != 0)
        die("renamed container content mismatch after reopen");
    rc = 0;
    free(got);
    free(want);
    vol_close(v);
    if (rc == 0) printf("F2MV-OK\n");
    return rc;
}

