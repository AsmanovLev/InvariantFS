/* ---- leg I: bitmap/journal divergence (WP22d open-time reconcile) ---- */
/* create the survivor, sync, and print the pba of its first segment (the
 * leg then clears that bit in the on-disk bitmap, simulating a bitmap
 * page dropped by a window while the journal append landed) */
static int cmd_f4mkdiv(const char *img)
{
    int err = 0;
    invfs_volume *v = vol_open(img, &err);
    uint64_t id, pba = 0;
    if (!v) die("open");
    id = create_pattern(v, "survivorS.bin", 192 * 1024, 55);
    if (vol_sync(v) != 0) die("sync");
    /* WP27: the segment's pba lives in the record's AST entry now; the
     * WAL is owner-only and never carries file maps */
    {
        uint64_t pos = vol_inode_area_start(v);
        while (pos) {
            uint32_t magic, rl;
            uint64_t ino, fsz, np;
            np = vol_inode_next(v, pos, &magic, &ino, &fsz, NULL, 0, &rl);
            if (!np) break;
            pos = np;
            if (magic != INODE_REC_MAGIC || ino != id) continue;
            {
                uint8_t *rb = malloc(rl);
                invfs_ast_hdr ah;
                if (rb && vol_read_raw(v, np - rl - 4, rb, rl) == 0) {
                    size_t base = (size_t)(invfs_rec_cbody(
                                       (const invfs_inode_rec *)rb) - rb);
                    if (invfs_ast_hdr_parse(rb + base, rl - base, &ah) == 0 &&
                        ah.num_blocks >= 1) {
                        const invfs_ast_block_entry *e =
                            (const invfs_ast_block_entry *)
                            (rb + base + ah.hdr_len);
                        if (e->length && e->pba)
                            pba = e->pba;
                    }
                }
                free(rb);
            }
            if (pba) break;
        }
    }
    if (!pba) die("no segment pba for the survivor");
    printf("F4MKDIV-OK pba=%llu\n", (unsigned long long)pba);
    vol_close(v);
    return 0;
}

/* after the sabotage: the open must reconcile (the survivor's block is
 * forced used), then a fresh write must NOT be allocated on it */
static int cmd_f4checkdiv(const char *img)
{
    int err = 0;
    invfs_volume *v = vol_open(img, &err);
    if (!v) die("open");
    assert_file(v, "survivorS.bin", 192 * 1024, 55);
    create_pattern(v, "attackerA.bin", 256 * 1024, 66);
    if (vol_sync(v) != 0) die("sync");
    assert_file(v, "survivorS.bin", 192 * 1024, 55);
    assert_file(v, "attackerA.bin", 256 * 1024, 66);
    vol_close(v);
    printf("F4CHECKDIV-OK\n");
    return 0;
}

/* WP27: mark the volume DIRTY with a valid CRC (the drop-window crash
 * shape; python lacks crc32c, so this runs here where invfs_crc32c is
 * linked in) */
static int cmd_f4dirty(const char *img)
{
    FILE *f = fopen(img, "r+b");
    invfs_superblock sb;
    if (!f) die("fopen");
    if (fseek(f, 0, SEEK_SET) != 0 ||
        fread(&sb, sizeof sb, 1, f) != 1) die("sb read");
    sb.state = INVFS_STATE_DIRTY;
    sb.checksum = invfs_crc32c(&sb, offsetof(invfs_superblock, checksum));
    if (fseek(f, 0, SEEK_SET) != 0 ||
        fwrite(&sb, sizeof sb, 1, f) != 1) die("sb write");
    fclose(f);
    printf("F4DIRTY-OK\n");
    return 0;
}

/* ---- leg E: renaming a swept container keeps its siblings ----------- */
static int cmd_f2cp(const char *img, const char *host, const char *name)
{
    int err = 0;
    invfs_volume *v = vol_open(img, &err);
    FILE *f;
    long len;
    uint8_t *buf;
    uint64_t id;
    if (!v) die("open");
    f = fopen(host, "rb");
    if (!f) die("host fopen");
    if (fseek(f, 0, SEEK_END) != 0 || (len = ftell(f)) < 0 ||
        fseek(f, 0, SEEK_SET) != 0) die("host size");
    buf = malloc((size_t)len);
    if (!buf) die("oom");
    if (fread(buf, 1, (size_t)len, f) != (size_t)len) die("host read");
    fclose(f);
    id = vol_create_file(v, name, buf, (size_t)len);
    free(buf);
    if (!id) die("create");
    vol_close(v);
    printf("F2CP-OK\n");
    return 0;
}

/* rename name->newname, then bit-compare newname against the host file,
 * in-session and after a full reopen */
static int cmd_f2mv(const char *img, const char *name, const char *newname,
                    const char *host)
{
    int err = 0;
    invfs_volume *v = vol_open(img, &err);
    FILE *f;
    long len;
    uint8_t *want, *got = NULL;
    size_t glen = 0;
    uint64_t id;
    int rc = 1;
    if (!v) die("open");
    f = fopen(host, "rb");
    if (!f) die("host fopen");
    if (fseek(f, 0, SEEK_END) != 0 || (len = ftell(f)) < 0 ||
        fseek(f, 0, SEEK_SET) != 0) die("host size");
    want = malloc((size_t)len);
    if (!want) die("oom");
    if (fread(want, 1, (size_t)len, f) != (size_t)len) die("host read");
    fclose(f);
    if (vol_rename(v, name, newname) != 0) die("rename");
    if (vol_find(v, name)) die("container source name survived the rename");
    id = vol_find(v, newname);
    if (!id) die("renamed container missing");
    if (vol_read_file(v, id, &got, &glen) != 0)
        die("renamed container unreadable in-session");
    if (glen != (size_t)len || memcmp(want, got, glen) != 0)
        die("renamed container content mismatch in-session");
    free(got); got = NULL;
    vol_close(v);
    v = vol_open(img, &err);
    if (!v) die("reopen");
    if (vol_find(v, name)) die("container source resurrected at reopen");
    id = vol_find(v, newname);
    if (!id) die("renamed container missing after reopen");
    if (vol_read_file(v, id, &got, &glen) != 0)
        die("renamed container unreadable after reopen");
    if (glen != (size_t)len || memcmp(want, got, glen) != 0)
        die("renamed container content mismatch after reopen");
    rc = 0;
    free(got);
    free(want);
    vol_close(v);
    if (rc == 0) printf("F2MV-OK\n");
    return rc;
}

int main(int argc, char **argv)
{
    if (argc < 3) {
        fprintf(stderr, "usage: harness <cmd> <img> [args]\n");
        return 2;
    }
    if (strcmp(argv[1], "f1run") == 0 && argc == 3)
        return cmd_f1run(argv[2]);
    if (strcmp(argv[1], "f1check") == 0 && argc == 3)
        return cmd_f1check(argv[2]);
    if (strcmp(argv[1], "f2rename") == 0 && argc == 3)
        return cmd_f2rename(argv[2]);
    if (strcmp(argv[1], "f2link") == 0 && argc == 3)
        return cmd_f2link(argv[2]);
    if (strcmp(argv[1], "f2mkdangle") == 0 && argc == 3)
        return cmd_f2mkdangle(argv[2]);
    if (strcmp(argv[1], "f2sabotage") == 0 && argc == 4)
