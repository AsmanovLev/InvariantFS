    vol_close(v);
    v = vol_open(img, &err);
    if (!v) die("reopen");
    if (vol_find(v, "fileC.bin")) die("deleted name still present");
    assert_file(v, "linkC.bin", 160 * 1024, 44);   /* after replay */
    vol_close(v);
    printf("F2LINK-OK\n");
    return 0;
}

/* ---- leg D: build the dangling live record (the leg-5 shape) ---------- */
static int cmd_f2mkdangle(const char *img)
{
    int err = 0;
    invfs_volume *v = vol_open(img, &err);
    uint64_t vid;
    if (!v) die("open");
    /* bystander FIRST: the victim's mappings must be the journal tail */
    create_pattern(v, "bystanderB.bin", 32 * 1024, 55);
    vid = create_pattern(v, "victimV.bin", 160 * 1024, 66);
    /* the survivor shares the victim's id (the rename fast path's shape) */
    if (vol_hardlink(v, "victimV.bin", "survivorS.bin") != 0)
        die("hardlink");
    vol_close(v);
    printf("F2MKDANGLE-OK victim_id=%llu\n", (unsigned long long)vid);
    return 0;
}

/* WP27: there are no file maps in the journal to drop -- the dangling
 * shape is the live record whose entries carry invalid pbas. Offline:
 * delete the victim's name through the engine (the id's blocks stay
 * referenced by the survivor twin's record), then zero the survivor's
 * live record's entry pbas in the image + restamp its CRC. The open
 * scan's consistent cut hides the record (never live); fsck counts the
 * invalid-pba entries as the miss and -f quarantines. */
static int cmd_f2sabotage(const char *img, uint64_t victim_id)
{
    int err = 0;
    invfs_volume *v = vol_open(img, &err);
    uint64_t last_pos = 0;
    if (!v) die("open");
    (void)victim_id;
    if (vol_delete_file(v, "victimV.bin") != 0) die("delete victim");
    if (vol_flush(v) != 0) die("flush");

    /* WP70: use vol_inode_next (mapper-aware) to locate the survivor record.
     * The legacy linear scan of the contiguous inode area missed records that
     * live in dynamic mapper extents (WP30). */
    {
        uint64_t pos = vol_inode_area_start(v);
        for (;;) {
            uint32_t magic, rl;
            uint64_t id, sz;
            char nm[INVFS_MAX_NAME + 1];
            uint64_t next = vol_inode_next(v, pos, &magic, &id, &sz,
                                           nm, sizeof nm, &rl);
            if (!next) break;
            if (magic == INODE_REC_MAGIC && strcmp(nm, "survivorS.bin") == 0)
                last_pos = pos;
            pos = next;
        }
    }
    vol_close(v);

    if (!last_pos) die("survivor record not found");

    /* offline: zero the survivor record's entry pbas + restamp its CRC */
    {
        FILE *f = fopen(img, "r+b");
        if (!f) die("fopen");
        {
            uint8_t *rb;
            invfs_inode_rec rh;
            invfs_ast_hdr ah;
            size_t base, ent0;
            uint32_t i, ncrc;
            if (fseek(f, (long)last_pos, SEEK_SET) != 0) die("seek");
            if (fread(&rh, sizeof rh, 1, f) != 1) die("rec head");
            if (rh.rec_len < INVFS_REC_HDR_LEN + 1 ||
                rh.rec_len > INVFS_MAX_REC_LEN)
                die("rec_len");
            rb = malloc(rh.rec_len);
            if (!rb) die("oom");
            if (fseek(f, (long)last_pos, SEEK_SET) != 0 ||
                fread(rb, rh.rec_len, 1, f) != 1) die("rec read");
            base = (size_t)(invfs_rec_cbody((const invfs_inode_rec *)rb) - rb);
            if (invfs_ast_hdr_parse(rb + base, rh.rec_len - base, &ah) != 0)
                die("recipe parse");
            ent0 = base + ah.hdr_len;
            if (ent0 + (size_t)ah.num_blocks *
                    sizeof(invfs_ast_block_entry) > rh.rec_len)
                die("entries oob");
            for (i = 0; i < ah.num_blocks; i++) {
                invfs_ast_block_entry *e = (invfs_ast_block_entry *)
                    (rb + ent0 + (size_t)i * sizeof *e);
                e->pba = 0;
            }
            ncrc = invfs_crc32c(rb, rh.rec_len);
            if (fseek(f, (long)last_pos, SEEK_SET) != 0 ||
                fwrite(rb, rh.rec_len, 1, f) != 1 ||
                fwrite(&ncrc, 4, 1, f) != 1)
                die("rec rewrite");
            free(rb);
        }
        fclose(f);
    }
    printf("F2SABOTAGE-OK\n");
    return 0;
}

