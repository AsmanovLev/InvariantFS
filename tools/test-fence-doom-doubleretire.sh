#!/bin/bash
# test-fence-doom-doubleretire.sh — WP630: fence-failure doom leaves a delete
# retire live across recreate, the next fence collects it twice (double -1 /
# double bitmap free; with a live dedupe sharer: EIO on live data).
#
# Leg 1 (accounting, deterministic): unlink A -> vol_delta_doom (exactly the
#   function the fence-failure paths call: volume.c flush "v3 bitmap" barrier
#   refusal, sync drain/barrier refusals) -> unlink A again -> sync. Both
#   retires name the SAME blocks (nothing was rewritten). The harness wraps
#   vol_free_blocks (ld --wrap) and fails if any pba is freed twice.
#   Pre-fix: DOUBLE free (R1 stale + R2). Post-fix: single (R1 dropped as a
#   stale generation).
# Leg 2 (end-to-end harm): A and B share one segment via in-session dedupe,
#   then the same doom cycle. Pre-fix the second -1 drives the shared pba's
#   refcount to 0 under live B -> B reads EIO. Post-fix B stays bit-exact.
#
# No vacuously-green legs: leg 1 asserts the double-fire ITSELF (pre-fix the
# harness must exit nonzero); leg 2 asserts the dedupe merge happened (free
# blocks up) before asserting readability.
#
# Run: INVFS_E2E_AGENT=wp630 bash tools/run-e2e.sh tools/test-fence-doom-doubleretire.sh
set -e
set -o pipefail

REPO="${REPO:-$(cd "$(dirname "$0")/.." && pwd)}"
B=$REPO/bin
WORK=/dev/shm/wp630
IMG1=wp630-double.img
IMG2=wp630-share.img
rm -rf "$WORK" && mkdir -p "$WORK"
cd "$WORK"
rm -f "$IMG1" "$IMG2"

fail() { echo "FAIL: $*" >&2; exit 1; }

OBJS="$(sed "s|^|$REPO/|" "$REPO/build/core_objs.txt")"
[ -f "$REPO/build/core_objs.txt" ] || fail "core_objs.txt missing (run make first)"

cat > "$WORK/dd_harness.c" <<'EOF'
/* dd_harness.c — WP630 engine driver (generated by
 * tools/test-fence-doom-doubleretire.sh). Links the engine objects.
 * --wrap=vol_free_blocks records every freed extent so leg 1 can assert
 * no pba is ever freed twice across the doom cycle. */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>
#include "volume.h"
#include "vol_delta.h"

static void die(const char *m) { fprintf(stderr, "HARNESS-FAIL: %s\n", m); exit(1); }

/* ---- --wrap ledgers ---- */
#define MAXFREES 4096
static uint64_t freed_pba[MAXFREES];
static uint64_t freed_len[MAXFREES];
static size_t nfreed;
static int record_on;

void __real_vol_free_blocks(invfs_volume *v, uint64_t pba, uint64_t nblocks);
void __wrap_vol_free_blocks(invfs_volume *v, uint64_t pba, uint64_t nblocks)
{
    if (record_on && nfreed < MAXFREES) {
        freed_pba[nfreed] = pba;
        freed_len[nfreed] = nblocks;
        nfreed++;
    }
    __real_vol_free_blocks(v, pba, nblocks);
}

/* vol_free_recipe_blocks releases: pre-fix the doom cycle releases the
 * same recipe twice, post-fix exactly once. */
#define RADDR_LEN 32u
static uint8_t rel_recipe[MAXFREES][32];
static size_t nrel;
int __real_vol_free_recipe_blocks(invfs_volume *v, const uint8_t *recipe_addr,
                                 uint64_t keep_pba);
int __wrap_vol_free_recipe_blocks(invfs_volume *v, const uint8_t *recipe_addr,
                                  uint64_t keep_pba)
{
    if (record_on && nrel < MAXFREES && recipe_addr) {
        memcpy(rel_recipe[nrel], recipe_addr, 32);
        nrel++;
    }
    return __real_vol_free_recipe_blocks(v, recipe_addr, keep_pba);
}

static void assert_single_release(void)
{
    size_t i, j;
    if (nrel == 0) die("no releases at all (control: retire never fired)");
    for (i = 0; i < nrel; i++) {
        for (j = i + 1; j < nrel; j++) {
            if (memcmp(rel_recipe[i], rel_recipe[j], 32) == 0) {
                fprintf(stderr, "HARNESS-FAIL: same recipe released twice "
                        "(releases %zu and %zu: stale + fresh delete-retire "
                        "both collected live)\n", i, j);
                exit(1);
            }
        }
    }
}

/* fail if any single block was freed more than once */
static void assert_no_double_free(void)
{
    size_t i, j;
    for (i = 0; i < nfreed; i++) {
        for (j = i + 1; j < nfreed; j++) {
            uint64_t a0 = freed_pba[i], a1 = a0 + freed_len[i];
            uint64_t b0 = freed_pba[j], b1 = b0 + freed_len[j];
            if (a0 < b1 && b0 < a1) {
                fprintf(stderr, "HARNESS-FAIL: pba range [%llu,%llu) freed twice "
                        "(entries %zu and %zu)\n",
                        (unsigned long long)(a0 > b0 ? a0 : b0),
                        (unsigned long long)(a1 < b1 ? a1 : b1), i, j);
                exit(1);
            }
        }
    }
}

static void fill_pattern(uint8_t *b, size_t n, uint64_t seed)
{
    uint64_t x = seed ? seed : 0x9E3779B97F4A7C15ull;
    size_t i;
    for (i = 0; i < n; i++) {
        x ^= x << 13; x ^= x >> 7; x ^= x << 17;
        b[i] = (uint8_t)(x >> 32);
    }
}

static void create_pattern(invfs_volume *v, const char *name, size_t len,
                           uint64_t seed)
{
    uint8_t *buf = malloc(len);
    uint64_t id;
    if (!buf) die("oom");
    fill_pattern(buf, len, seed);
    id = vol_create_file(v, name, buf, len);
    free(buf);
    if (!id) die("create failed");
}

uint32_t pba_ref_count(invfs_volume *v, uint64_t pba);
int vol_recipe_load(invfs_volume *v, const uint8_t *addr, uint8_t **blob_out,
                     size_t *blen_out);
int vol_ast_recipe_parse(const uint8_t *blob, size_t blen, invfs_ast_hdr *hdr_out,
                          const invfs_ast_block_entry **ents_out, size_t *nents_out);

/* first non-TEXT data pba B's live recipe names (0 = none) */
static uint64_t survivor_pba(invfs_volume *v, const char *name)
{
    uint64_t id = vol_find(v, name);
    invfs_inode in;
    uint8_t *blob = NULL;
    size_t blen = 0;
    invfs_ast_hdr ah;
    const invfs_ast_block_entry *ents = NULL;
    size_t nents = 0, i;
    uint64_t pba = 0;
    if (!id) die("survivor_pba: absent");
    if (vol_inode_get(v, id, &in) != 1) die("survivor_pba: row unreadable");
    if (vol_recipe_load(v, in.recipe_addr, &blob, &blen) != 0 || !blob)
        die("survivor_pba: recipe unloadable");
    if (vol_ast_recipe_parse(blob, blen, &ah, &ents, &nents) != 0 || !ents)
        die("survivor_pba: recipe unparseable");
    for (i = 0; i < nents; i++) {
        if (ents[i].pba && ents[i].zone != INVFS_ZONE_TEXT) { pba = ents[i].pba; break; }
    }
    free(blob);
    if (!pba) die("survivor_pba: no data pba (control)");
    return pba;
}

static void assert_gone(invfs_volume *v, const char *name)
{
    if (vol_find(v, name)) die("file should be gone");
}

static void assert_content(invfs_volume *v, const char *name, size_t len,
                           uint64_t seed)
{
    uint64_t id = vol_find(v, name);
    uint8_t *buf = NULL, *want;
    size_t blen = 0;
    if (!id) die("assert_content: absent");
    if (vol_read_file(v, id, &buf, &blen) != 0) die("assert_content: EIO read");
    if (blen != len) die("assert_content: size");
    want = malloc(len);
    if (!want) die("oom");
    fill_pattern(want, len, seed);
    if (memcmp(want, buf, len) != 0) die("assert_content: bytes differ");
    free(want);
    free(buf);
}

/* leg 1: unlink -> doom -> unlink -> sync; the same recipe must be
 * released EXACTLY once. Pre-fix both the stale (R1) and the fresh (R2)
 * delete-retire collect live and vol_free_recipe_blocks runs twice on the
 * identical recipe (the second -1 is masked from the bitmap gate by the
 * first free, but the refcount is already corrupted -- leg 2 shows the
 * EIO that follows when a live sharer exists). */
static int cmd_account(const char *img)
{
    int err = 0;
    invfs_volume *v = vol_open(img, &err);
    if (!v) die("open");
    create_pattern(v, "A.bin", 100 * 1024, 41);
    if (vol_sync(v) != 0) die("setup sync failed");
    if (vol_unlink(v, "A.bin") != 0) die("first unlink failed");
    /* the fence-failure doom, exactly as the refused-barrier paths call it */
    vol_delta_doom(v);
    if (!vol_find(v, "A.bin")) die("doom did not restore the row (control)");
    if (vol_unlink(v, "A.bin") != 0) die("second unlink failed");
    nfreed = 0;
    nrel = 0;
    record_on = 1;
    if (vol_sync(v) != 0) die("final sync failed");
    record_on = 0;
    fprintf(stderr, "harness: leg1 final sync: %zu release(s), %zu extent(s)\n",
            nrel, nfreed);
    assert_single_release();
    assert_no_double_free();
    assert_gone(v, "A.bin");
    vol_close(v);
    return 0;
}

/* leg 2: dedupe-shared segment + doom cycle. Mechanism: the shared recipe
 * must be released exactly once (wrap). Harm, made concrete: after the
 * drain the shared pba's refcount must be 1 (live B still names it);
 * pre-fix the stale + fresh retires drive it 2 -> 1 -> 0 and free P under
 * live B (in-session reads still hit ARC, so the count -- not the read --
 * is the deterministic signal). */
static int cmd_share(const char *img)
{
    int err = 0;
    invfs_volume *v = vol_open(img, &err);
    uint64_t free_before, free_merged;
    if (!v) die("open");
    create_pattern(v, "A.bin", 100 * 1024, 77);
    create_pattern(v, "B.bin", 100 * 1024, 77);   /* identical content */
    if (vol_sync(v) != 0) die("setup sync failed");
    free_before = vol_count_free(v);
    if (vol_sweep_dedupe(v) < 0) die("dedupe pass failed");
    if (vol_sync(v) != 0) die("post-dedupe sync failed");
    free_merged = vol_count_free(v);
    fprintf(stderr, "harness: leg2 free before=%llu merged=%llu\n",
            (unsigned long long)free_before, (unsigned long long)free_merged);
    if (free_merged <= free_before)
        die("dedupe did not merge (control: no shared pba, leg invalid)");
    if (vol_unlink(v, "A.bin") != 0) die("first unlink failed");
    vol_delta_doom(v);
    if (!vol_find(v, "A.bin")) die("doom did not restore the row (control)");
    if (vol_unlink(v, "A.bin") != 0) die("second unlink failed");
    nfreed = 0;
    nrel = 0;
    record_on = 1;
    if (vol_sync(v) != 0) die("final sync failed");
    record_on = 0;
    fprintf(stderr, "harness: leg2 final sync: %zu release(s)\n", nrel);
    assert_single_release();
    assert_gone(v, "A.bin");
    assert_content(v, "B.bin", 100 * 1024, 77);   /* sanity (ARC may mask) */
    {
        uint64_t p = survivor_pba(v, "B.bin");
        uint32_t c = pba_ref_count(v, p);
        fprintf(stderr, "harness: leg2 shared pba=%llu refcount=%u\n",
                (unsigned long long)p, c);
        if (c != 1) {
            fprintf(stderr, "HARNESS-FAIL: shared pba refcount %u under live "
                    "sharer B.bin (want 1: stale retire double-charged it)\n", c);
            exit(1);
        }
    }
    vol_close(v);
    return 0;
}

int main(int argc, char **argv)
{
    if (argc != 3) { fprintf(stderr, "usage: %s account|share img\n", argv[0]); return 2; }
    if (!strcmp(argv[1], "account")) return cmd_account(argv[2]);
    if (!strcmp(argv[1], "share")) return cmd_share(argv[2]);
    return 2;
}
EOF

gcc -std=gnu11 -O2 -I$REPO/src -I$REPO/src/core -I$REPO/src/codecs -I$REPO/src/recipes -I$REPO/src/vendor7z -o "$WORK/dd_harness" \
    "$WORK/dd_harness.c" $OBJS -Wl,--wrap=vol_free_blocks -Wl,--wrap=vol_free_recipe_blocks -Wl,-l:libzstd.so.1 -lz -lpthread \
    || fail "harness build"
H=$WORK/dd_harness

echo "== leg 1: doom-cycle accounting (no pba freed twice) =="
$B/invf-mkfs "$IMG1" 0.0625 >"$WORK/mkfs1.log" || fail "mkfs 1"
"$H" account "$IMG1" 2>"$WORK/leg1.log" || { cat "$WORK/leg1.log"; fail "leg1: double free (bug present)"; }
cat "$WORK/leg1.log"
$B/invf-fsck "$IMG1" >"$WORK/fsck1.log" 2>&1 || fail "fsck leg1 failed"
grep -q "^OK$" "$WORK/fsck1.log" || { cat "$WORK/fsck1.log"; fail "fsck leg1 not OK"; }
echo "  leg1 green + fsck OK"

echo "== leg 2: dedupe sharer survives the doom cycle =="
$B/invf-mkfs "$IMG2" 0.0625 >"$WORK/mkfs2.log" || fail "mkfs 2"
"$H" share "$IMG2" 2>"$WORK/leg2.log" || { cat "$WORK/leg2.log"; fail "leg2: survivor damaged (bug present)"; }
cat "$WORK/leg2.log"
$B/invf-fsck "$IMG2" >"$WORK/fsck2.log" 2>&1 || fail "fsck leg2 failed"
grep -q "^OK$" "$WORK/fsck2.log" || { cat "$WORK/fsck2.log"; fail "fsck leg2 not OK"; }
echo "  leg2 green + fsck OK"

echo "PASS: fence-doom double-retire clean"
