/*
 * fuzz_manifest.c — manifest parser fuzz harness (fuzz wave 4/4).
 *
 * Feeds malformed codecpack manifests through the REAL registration path
 * (pack_scan_dir -> parse_manifest -> pack_register, all inside codec.o)
 * by pointing INVFS_CODECPACKS at a temp dir holding exactly one
 * fixture .codecpack per case, calling invfs_codec_probe_reset() and then
 * forcing a registry rebuild (invfs_codec_all). After each registration
 * the registry is exercised: probe() every codec (access() checks over
 * the fuzzed argv templates) and sniff() with a random head buffer and a
 * fuzzed filename (exercises the fuzzed sniff.magic/sniff.ext rules).
 *
 * The exec hooks are stubs (the codec_test.c convention): no fuzzed argv
 * is ever executed.
 *
 * INVARIANT: registration never crashes and never half-registers; a
 * registered pack has a nonempty name and algo < 64 (the AST field
 * bound pack_register documents). A crash aborts the process; the last
 * "CASE nnnnn" line on stdout names the culprit, and the manifest is
 * kept at <cases>/case_nnnnn.manifest (also regenerated by --only N).
 *
 * Build (tools/test-fuzz.sh does this):
 *   gcc -std=gnu11 -O2 -I src -o fuzz_manifest \
 *       tools/fuzz/fuzz_manifest.c build/obj/{codec,ppmd8,ppmd8enc,\
 *       ppmd8dec,ppmd_codec,lz4,bcj_x86}.o -Wl,-l:libzstd.so.1 -lz -lpthread
 *
 * Run:  fuzz_manifest [iterations=200] [seed=0xCAFE] [--only N]
 */
