# ---- crash legs -------------------------------------------------------------
# $1=image $2=abort stage $3=files $4=rounds
crash_leg() {
    local img=$1 stage=$2 F=$3 R=$4
    local ub rc
    echo "== [crash:$stage] kill -9 mid-compaction, recover =="
    $B/invf-mkfs "$img" 0.25 >/dev/null || fail "mkfs $img"
    if [ "$(is_mapper "$img")" = 1 ]; then
        echo "  crash:$stage SKIPPED on a mapper volume: the CMP0 linear-
  compaction crash protocol is unreachable there (vol_inode_compact refuses;
  consolidation is the sweep meta-merge, whose crash-safety rides the ordinary
  record-append + journal machinery covered by test-mapper-crash)"
        return 0
    fi
    "$H" churn "$img" "$F" "$R" >/dev/null || fail "churn $img"
    ub=$(used_of "$img")
    set +e
    INVFS_COMPACT_ABORT_AT=$stage $B/invf-sweep "$img" --compact \
        > "$WORK/abort-$stage.log" 2>&1
    rc=$?
    set -e
    [ "$rc" = "137" ] || { cat "$WORK/abort-$stage.log"; fail "$stage: rc=$rc, want 137"; }
    if [ "$stage" = "staged" ]; then
        # pre-arm: the old area is byte-intact, no latch, no descriptor;
        # the stranded staging run is an ordinary orphan for fsck
        "$H" cmpend "$img" | grep -q "pending=0" || fail "$stage: CMP0 armed?!"
        "$H" wrena "$img" | grep -q "write_enabled=1" || fail "$stage: volume latched?!"
        [ "$(used_of "$img")" = "$ub" ] || fail "$stage: area moved pre-arm"
        set +e
        $B/invf-fsck "$img" -f > "$WORK/fsck-$stage.log" 2>&1
        rc=$?
        set -e
        [ "$rc" = "0" ] || [ "$rc" = "3" ] || { cat "$WORK/fsck-$stage.log"; fail "$stage: fsck -f rc=$rc"; }
        grep -qE "^  orphans:      [1-9]" "$WORK/fsck-$stage.log" \
            || { cat "$WORK/fsck-$stage.log"; fail "$stage: stranded staging not an orphan"; }
        $B/invf-fsck "$img" | tail -1 | grep -q "^OK$" || fail "$stage: fsck not clean"
        "$H" verify "$img" "$F" "$R" || fail "$stage: content wrong"
        # a plain re-run completes the pass
        $B/invf-sweep "$img" --compact > "$WORK/compact-$stage.log" 2>&1 \
            || fail "$stage: re-compact failed"
        grep -q "^inode area compacted: " "$WORK/compact-$stage.log" \
            || fail "$stage: re-run did not compact"
    else
        # armed/copying/copied: CMP0 + the read-only latch survive; the
        # volume must latch needs-recovery, sweep refuses, fsck -f rolls
        # the verified staging forward (idempotent)
        "$H" cmpend "$img" | grep -q "pending=1" || fail "$stage: CMP0 not armed"
        "$H" wrena "$img" | grep -q "write_enabled=0" || fail "$stage: volume not latched"
        $B/invf-fsck "$img" > "$WORK/fsckro-$stage.log" 2>&1 || true
        grep -q "an interrupted inode-area compaction is pending" \
            "$WORK/fsckro-$stage.log" \
            || { cat "$WORK/fsckro-$stage.log"; fail "$stage: no pending notice"; }
        set +e
        $B/invf-sweep "$img" > "$WORK/sweepref-$stage.log" 2>&1
        rc=$?
        set -e
        [ "$rc" != "0" ] || fail "$stage: sweep ran with CMP0 armed"
        grep -q "interrupted inode-area compaction is pending" \
            "$WORK/sweepref-$stage.log" || fail "$stage: sweep did not refuse"
        set +e
        $B/invf-fsck "$img" -f > "$WORK/fsck-$stage.log" 2>&1
        rc=$?
        set -e
        [ "$rc" = "0" ] || [ "$rc" = "3" ] || { cat "$WORK/fsck-$stage.log"; fail "$stage: fsck -f rc=$rc"; }
        grep -q "compaction: interrupted pass rolled forward" \
            "$WORK/fsck-$stage.log" || { cat "$WORK/fsck-$stage.log"; fail "$stage: no roll-forward"; }
        $B/invf-fsck "$img" | tail -1 | grep -q "^OK$" || fail "$stage: fsck not clean"
        $B/invf-verify "$img" --deep | tail -1 | grep -q " 0 corrupt," \
            || fail "$stage: verify --deep not clean"
        "$H" verify "$img" "$F" "$R" || fail "$stage: content wrong"
        "$H" cmpend "$img" | grep -q "pending=0" || fail "$stage: CMP0 survived recovery"
        # the recovered area is the compacted one
        [ "$(used_of "$img")" -lt "$ub" ] || fail "$stage: area not compacted"
        [ "$(used_of "$img")" = "$(live_of "$img")" ] || fail "$stage: area != live set"
    fi
    echo "  $stage: recovered, bit-exact, fsck/verify clean"
}

