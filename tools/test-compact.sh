class_of() { $B/meta_probe "$1" --heat "$2" 2>/dev/null | sed -n 's/^class=\([0-9a-z]*\).*/\1/p'; }
used_of()  { "$H" areastat "$1" | sed -n 's/^used=\([0-9]*\).*/\1/p'; }
live_of()  { "$H" areastat "$1" | sed -n 's/.* live=\([0-9]*\)$/\1/p'; }

# WP71h: mapper detection. Every volume the current mkfs produces is a
# mapper volume (MET0 + dynamic metadata extents, sb.meta_mapper_pba != 0):
# the legacy LINEAR inode-area compaction (legs A1-A8 and the CMP0 crash
# legs) is unreachable on them -- vol_inode_compact refuses loudly and the
# mapper-era consolidation is the sweep's meta-merge (vol_meta_merge_run).
# The M-legs below exercise that contract; the legacy legs stay intact for
# pre-WP30 volumes.
is_mapper() { python3 - "$1" <<'PY'
import struct, sys
d = open(sys.argv[1], "rb").read(0xA8)
print(1 if struct.unpack_from("<Q", d, 0x98)[0] else 0)
PY
}
extent_blocks() { $B/invf-stats "$1" 2>/dev/null | \
    sed -n 's/^meta extents (WP30): [0-9]* extent(s), \([0-9]*\) blocks.*/\1/p' | \
    head -1 | sed 's/^$/0/'; }

echo "== [A] churn -> inode area grows -> compaction =="
INVFS_META_FRAC=8 $B/invf-mkfs "$IMG_A" 0.25 >/dev/null || fail "mkfs A"
"$H" churn "$IMG_A" 40 24 || fail "churn A"
"$H" verify "$IMG_A" 40 24 || fail "pre-sweep content wrong"
UA0=$(used_of "$IMG_A"); LA0=$(live_of "$IMG_A")
echo "  after churn: used=$UA0 live=$LA0"
[ "$UA0" -gt 0 ] && [ "$LA0" -gt 0 ] || fail "areastat"
[ $(( (UA0 - LA0) * 10 )) -gt $(( UA0 * 3 )) ] || fail "churn did not produce >30% dead bytes"

MAPPER=$(is_mapper "$IMG_A")
if [ "$MAPPER" = 1 ]; then
echo "== [M1] mapper volume: sweep arms a checkpoint; the linear compaction refuses LOUDLY =="
$B/invf-sweep "$IMG_A" > "$WORK/sweep-m1.log" 2>&1 || { cat "$WORK/sweep-m1.log"; fail "sweep M1"; }
grep -q "checkpoint: #1 armed" "$WORK/sweep-m1.log" || fail "M1: no checkpoint armed"
grep -q "inode compact: skipped (mapper volume" "$WORK/sweep-m1.log" \
    || { cat "$WORK/sweep-m1.log"; fail "M1: no loud mapper-compaction refusal"; }
if grep -q "^inode area compacted: " "$WORK/sweep-m1.log"; then
    fail "M1: linear compaction ran on a mapper volume"
fi
"$H" ckp "$IMG_A" | grep -q "present=1" || fail "M1: CKP0 not live"
"$H" verify "$IMG_A" 40 24 || fail "M1: content wrong"
echo "  loud refusal under the live checkpoint; content intact"

echo "== [M2] --compact on a mapper volume: loud refusal, extent footprint untouched =="
XB0=$(extent_blocks "$IMG_A")
[ "$XB0" -gt 0 ] || fail "M2: no extent footprint reported (invf-stats meta extents line)"
$B/invf-sweep "$IMG_A" --compact > "$WORK/compact-m2.log" 2>&1 || fail "M2: --compact rc"
grep -q "inode compact: skipped (mapper volume" "$WORK/compact-m2.log" \
    || { cat "$WORK/compact-m2.log"; fail "M2: no mapper skip message"; }
if grep -q "^inode area compacted: " "$WORK/compact-m2.log"; then fail "M2: compacted"; fi
XB1=$(extent_blocks "$IMG_A")
[ "$XB0" = "$XB1" ] || fail "M2: extent footprint moved ($XB0 -> $XB1)"
"$H" verify "$IMG_A" 40 24 || fail "M2: content wrong after the refused compact"
$B/invf-fsck "$IMG_A" | grep -q "^OK$" || fail "M2: fsck not clean under the live checkpoint"
echo "  footprint stable at $XB1 blocks; fsck clean"

echo "== [M3] realize + re-sweep: the mapper-era consolidation is the meta-merge =="
$B/invf-sweep "$IMG_A" --realize > "$WORK/realize-m3.log" 2>&1 || { cat "$WORK/realize-m3.log"; fail "realize M3"; }
grep -q "realized" "$WORK/realize-m3.log" || fail "M3: no realize line"
"$H" ckp "$IMG_A" | grep -q "present=0" || fail "M3: checkpoint survived realize"
$B/invf-sweep "$IMG_A" > "$WORK/sweep-m3.log" 2>&1 || { cat "$WORK/sweep-m3.log"; fail "sweep M3"; }
"$H" verify "$IMG_A" 40 24 || fail "M3: content wrong after realize+re-sweep"
$B/invf-fsck "$IMG_A" | grep -q "^OK$" || fail "M3: fsck not clean"
$B/invf-verify "$IMG_A" --deep | grep -q " 0 corrupt," || fail "M3: verify not clean"
XB2=$(extent_blocks "$IMG_A")
echo "  merge-on-sweep contract OK (extent footprint $XB2 blocks); content bit-exact"
$B/invf-sweep "$IMG_A" --realize >/dev/null 2>&1 || true
echo "== [A4-A8] linear-compaction legs: SKIPPED on a mapper volume (CMP0 machinery unreachable; the meta-merge owns consolidation) =="
else

echo "== [A1] sweep: checkpoint live -> auto-compaction skipped =="
$B/invf-sweep "$IMG_A" > "$WORK/sweep-a1.log" 2>&1 || { cat "$WORK/sweep-a1.log"; fail "sweep A1"; }
grep -q "checkpoint: #1 armed" "$WORK/sweep-a1.log" || fail "A1: no checkpoint armed"
grep -q "inode compact: skipped (sweep checkpoint" "$WORK/sweep-a1.log" \
    || { cat "$WORK/sweep-a1.log"; fail "A1: no checkpoint-skip message"; }
if grep -q "^inode area compacted: " "$WORK/sweep-a1.log"; then
    fail "A1: compacted under a live checkpoint"
fi
"$H" ckp "$IMG_A" | grep -q "present=1" || fail "A1: CKP0 not live"
UA1S=$(used_of "$IMG_A")
echo "  auto-compaction skipped under the live checkpoint"

echo "== [A2] --compact with CKP0 live: skipped with a message =="
$B/invf-sweep "$IMG_A" --compact > "$WORK/compact-a2.log" 2>&1 || fail "A2 rc"
grep -q "inode compact: skipped (sweep checkpoint" "$WORK/compact-a2.log" \
    || { cat "$WORK/compact-a2.log"; fail "A2: no skip message"; }
if grep -q "compacted" "$WORK/compact-a2.log"; then fail "A2: compacted under a live checkpoint"; fi
[ "$(used_of "$IMG_A")" = "$UA1S" ] || fail "A2: area moved"
# the refusal is total: content + structures untouched, fsck clean
"$H" verify "$IMG_A" 40 24 || fail "A2: content wrong after the refused compact"
$B/invf-fsck "$IMG_A" > "$WORK/fsck-a2.log" 2>&1 || true
grep -q "^OK$" "$WORK/fsck-a2.log" \
    || { cat "$WORK/fsck-a2.log"; fail "A2: fsck not clean under the live checkpoint"; }
echo "  volume untouched (content bit-exact, fsck OK)"

echo "== [A3] checkpoint realized -> compaction runs (auto) =="
$B/invf-sweep "$IMG_A" --realize > "$WORK/realize-a3.log" 2>&1 \
    || { cat "$WORK/realize-a3.log"; fail "realize A3"; }
grep -q "checkpoint: previous run realized" "$WORK/realize-a3.log" \
    || fail "A3: no realize line"
grep -q "^inode area compacted: " "$WORK/realize-a3.log" \
    || { cat "$WORK/realize-a3.log"; fail "A3: no compaction line"; }
grep "^inode area compacted: " "$WORK/realize-a3.log"
"$H" ckp "$IMG_A" | grep -q "present=0" || fail "A3: checkpoint survived"
UA1=$(used_of "$IMG_A"); LA1=$(live_of "$IMG_A")
echo "  after compaction: used=$UA1 live=$LA1 (post-sweep used was $UA1S)"
[ "$UA1" -lt "$UA1S" ] || fail "A3: area did not shrink"
[ "$UA1" = "$LA1" ] || fail "A3: compacted area is not exactly the live set"
"$H" verify "$IMG_A" 40 24 || fail "A3: content wrong after compaction"
# batched text survived the cut (the \x01tzb owner is a live record too)
[ "$(class_of "$IMG_A" c00.txt)" = "7" ] || fail "A3: c00.txt not TEXT post-compaction"
$B/invf-ls "$IMG_A" | grep -q "sub/g00" || fail "A3: directory subtree lost"
$B/invf-verify "$IMG_A" --deep | tail -1 | grep -q " 0 corrupt," \
    || fail "A3: verify --deep not clean"
$B/invf-fsck "$IMG_A" > "$WORK/fsck-a3.log" 2>&1 || true
grep -q "^OK$" "$WORK/fsck-a3.log" || { cat "$WORK/fsck-a3.log"; fail "A3: fsck not clean"; }
echo "  live files bit-exact, batched text + subtree intact, fsck/verify clean"

echo "== [A4] quiescent re-sweep: no waste, no compaction =="
# WP27: the churn legs left every file write-hot (wheat ~= #rounds). The
# next sweeps do real decay work -- one record append per heat-carrying
# file per run (v1 hid exactly that churn in the journal pads; format v2
# carries heat in the records themselves, so the dead versions pile up in
# the inode area and the auto-compaction legitimately reclaims them).
# Cool the heat with idle sweeps first; the final re-sweep must be
# quiescent (nothing to decay, nothing to sweep) and compact nothing.
for i in $(seq 30); do
    $B/invf-sweep "$IMG_A" >/dev/null 2>&1 || fail "A4 cooling sweep $i"
done
$B/invf-sweep "$IMG_A" > "$WORK/sweep-a4.log" 2>&1 || fail "sweep A4"
if grep -q "^inode area compacted: " "$WORK/sweep-a4.log"; then
    fail "A4: compaction refired on a compact area"
fi
"$H" verify "$IMG_A" 40 24 || fail "A4: content wrong"

echo "== [A5] INVFS_NO_COMPACT=1 disables the automatic pass =="
"$H" churn "$IMG_A" 40 12 >/dev/null || fail "churn A5"
# run 1 (env off): the RAW rewrites are swept, blocks retire into the
# retention registry, CKP0 stays live -- compaction is gated by the
# checkpoint anyway; run 2 (env off) is the quiescent checkpoint-free end
# state where ONLY the env can be what suppresses the pass
INVFS_NO_COMPACT=1 $B/invf-sweep "$IMG_A" > "$WORK/sweep-a5a.log" 2>&1 \
    || { cat "$WORK/sweep-a5a.log"; fail "sweep A5a"; }
INVFS_NO_COMPACT=1 $B/invf-sweep "$IMG_A" > "$WORK/sweep-a5b.log" 2>&1 \
    || { cat "$WORK/sweep-a5b.log"; fail "sweep A5b"; }
