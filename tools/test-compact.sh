/* cpharness.c — WP22e engine-level test driver (generated by
 * tools/test-compact.sh; links the engine objects, public API only).
 *
 *   cpharness churn  <img> <F> <R>   the churn scenario (below)
 *   cpharness verify <img> <F> <R>   assert the final state bit-exactly
 *   cpharness areastat <img>         "used=.. live=.." (inode area bytes)
 *   cpharness ckp      <img>         "present=<0|1>" (CKP0 live)
 *   cpharness cmpend   <img>         "pending=<0|1>" (CMP0 armed)
 *   cpharness wrena    <img>         "write_enabled=<0|1>"
 *   cpharness readonly <img> <0|1>   operator read-only hold + flush
 *
 * The churn scenario (deterministic): files f%03d (base 0) and
 * sub/g%02d (base 100) are REWRITTEN every round r < R with
 * bin_pattern(base, r); one victim per round is deleted+recreated;
 * doomed d%02d (base 200) exist only for r < R/3 (deleted at R/3);
 * cold c%02d.txt (base 300) are written ONCE at round R-1. So every
 * survivor's final content is gen(base, R-1) and the doomed are absent.
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>
#include "volume.h"
#include "invarifs.h"

static void die(const char *m) { fprintf(stderr, "HARNESS-FAIL: %s\n", m); exit(1); }

static void fill_pattern(uint8_t *b, size_t n, uint64_t key)
{
    uint64_t x = key * 0x9E3779B97F4A7C15ull + 0x123456789;
    size_t i;
    for (i = 0; i < n; i++) {
        x ^= x << 13; x ^= x >> 7; x ^= x << 17;
        b[i] = (uint8_t)(x >> 32);
    }
}

/* printable text, same determinism (the .txt cold files are PPMd-batch
 * candidates -- content must sniff as text) */
static void text_pattern(uint8_t *b, size_t n, uint64_t key)
{
    static const char *WORDS[] = { "the","quick","brown","fox","jumps",
        "over","lazy","dogs","int","static","return","while","for" };
    size_t i = 0;
    uint64_t x = key * 0x9E3779B97F4A7C15ull + 777;
    while (i < n) {
        const char *w = WORDS[(x >> 24) % 13];
        size_t wl = strlen(w), k;
        x ^= x << 13; x ^= x >> 7; x ^= x << 17;
        for (k = 0; k < wl && i < n; k++) b[i++] = (uint8_t)w[k];
        if (i < n) b[i++] = (i % 71 == 70) ? '\n' : ' ';
    }
}

static size_t file_len(uint64_t base, int r)
{
    return 1200 + (size_t)((base * 997 + (uint64_t)r * 13) % 5200);
}

static void gen_file(uint8_t **buf, size_t *len, uint64_t base, int r,
                     int text)
{
    *len = file_len(base, r);
    *buf = malloc(*len);
    if (!*buf) die("oom");
    if (text) text_pattern(*buf, *len, base * 1000 + (uint64_t)r);
    else      fill_pattern(*buf, *len, base * 1000 + (uint64_t)r);
}

static void put_file(invfs_volume *v, const char *name, uint64_t base, int r,
                     int text)
{
    uint8_t *buf; size_t len;
    gen_file(&buf, &len, base, r, text);
    if (strchr(name, '/')) vol_ensure_path(v, name);
    if (!vol_replace_file(v, name, buf, len)) die("replace_file");
    free(buf);
}

static int cmd_churn(const char *img, long F, long R)
{
    int err = 0;
    invfs_volume *v = vol_open(img, &err);
    long f, g, c, d;
    int r;
    char nm[64];
    if (!v) die("open");
    for (r = 0; r < R; r++) {
        for (f = 0; f < F; f++) {
            snprintf(nm, sizeof nm, "f%03ld", f);
            put_file(v, nm, (uint64_t)f, r, 0);
        }
        for (g = 0; g < 4; g++) {
            snprintf(nm, sizeof nm, "sub/g%02ld", g);
            put_file(v, nm, (uint64_t)(100 + g), r, 0);
        }
        /* one victim deleted+recreated per round (kill-by-id churn) */
        {
            long victim = (r * 7) % F;
            snprintf(nm, sizeof nm, "f%03ld", victim);
            if (vol_delete_file(v, nm) != 0) die("victim delete");
            put_file(v, nm, (uint64_t)victim, r, 0);
        }
        /* doomed files: live only for the first third of the rounds */
        for (d = 0; d < 5; d++) {
            snprintf(nm, sizeof nm, "d%02ld", d);
            if (r < R / 3)
                put_file(v, nm, (uint64_t)(200 + d), r, 0);
            else if (r == R / 3)
                vol_delete_file(v, nm);   /* -1 when never created: fine */
        }
        /* cold text files: written once, at the last round */
        if (r == R - 1) {
            for (c = 0; c < 6; c++) {
                snprintf(nm, sizeof nm, "c%02ld.txt", c);
                put_file(v, nm, (uint64_t)(300 + c), r, 1);
            }
        }
    }
    if (vol_flush(v) != 0) die("flush");
    vol_close(v);
    printf("CHURN-OK\n");
    return 0;
}

static void assert_file(invfs_volume *v, const char *name, uint64_t base,
                        int r, int text)
{
    uint64_t id = vol_find(v, name);
    uint8_t *buf = NULL, *want;
    size_t blen = 0, wlen;
    if (!id) die("assert_file: absent");
    if (vol_read_file(v, id, &buf, &blen) != 0) die("assert_file: read");
    gen_file(&want, &wlen, base, r, text);
    if (blen != wlen || memcmp(want, buf, wlen) != 0)
        die("assert_file: content mismatch");
    free(want);
    free(buf);
}

static int cmd_verify(const char *img, long F, long R)
{
    int err = 0;
    invfs_volume *v = vol_open(img, &err);
    long f, g, c, d;
    char nm[64];
    if (!v) die("open");
    for (f = 0; f < F; f++) {
        snprintf(nm, sizeof nm, "f%03ld", f);
        assert_file(v, nm, (uint64_t)f, (int)R - 1, 0);
    }
    for (g = 0; g < 4; g++) {
        snprintf(nm, sizeof nm, "sub/g%02ld", g);
        assert_file(v, nm, (uint64_t)(100 + g), (int)R - 1, 0);
    }
    for (c = 0; c < 6; c++) {
        snprintf(nm, sizeof nm, "c%02ld.txt", c);
        assert_file(v, nm, (uint64_t)(300 + c), (int)R - 1, 1);
    }
    for (d = 0; d < 5; d++) {
        snprintf(nm, sizeof nm, "d%02ld", d);
        if (vol_find(v, nm)) die("doomed file present");
    }
    vol_close(v);
    printf("VERIFY-OK\n");
    return 0;
}

int main(int argc, char **argv)
{
    if (argc < 3) return 2;
    if (!strcmp(argv[1], "churn") && argc == 5)
        return cmd_churn(argv[2], atol(argv[3]), atol(argv[4]));
    if (!strcmp(argv[1], "verify") && argc == 5)
        return cmd_verify(argv[2], atol(argv[3]), atol(argv[4]));
    if (!strcmp(argv[1], "areastat") && argc == 3) {
        int err = 0;
        invfs_volume *v = vol_open(argv[2], &err);
        if (!v) die("open");
        printf("used=%llu live=%llu\n",
               (unsigned long long)(vol_inode_area_pos(v) -
                                    vol_inode_area_start(v)),
               (unsigned long long)vol_inode_live_bytes(v));
        vol_close(v);
        return 0;
    }
    if (!strcmp(argv[1], "ckp") && argc == 3) {
        int err = 0;
        invfs_volume *v = vol_open(argv[2], &err);
        if (!v) die("open");
        printf("present=%d\n", vol_ckp_armed(v));
        vol_close(v);
        return 0;
    }
    if (!strcmp(argv[1], "cmpend") && argc == 3) {
        int err = 0;
        invfs_volume *v = vol_open(argv[2], &err);
        if (!v) die("open");
        printf("pending=%d\n", vol_compact_pending(v));
        vol_close(v);
        return 0;
    }
    if (!strcmp(argv[1], "wrena") && argc == 3) {
        int err = 0;
        invfs_volume *v = vol_open(argv[2], &err);
        if (!v) die("open");
        printf("write_enabled=%d\n", vol_write_enabled(v));
        vol_close(v);
        return 0;
    }
    if (!strcmp(argv[1], "readonly") && argc == 4) {
        int err = 0;
        invfs_volume *v = vol_open(argv[2], &err);
        if (!v) die("open");
        vol_set_readonly(v, atoi(argv[3]));
        if (vol_flush(v) != 0) die("flush");
        vol_close(v);
        return 0;
    }
    fprintf(stderr, "bad args\n");
    return 2;
}
