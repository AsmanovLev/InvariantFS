#!/bin/bash
# test-compact.sh — WP22e e2e: online inode-area compaction (hot tail
# pruning) + invf-sweep --fast. Persistent regression suite.
#
#   Leg A (churn -> compact): an engine-level churn workload (create /
#   rewrite / delete, repeatedly) grows the append-only inode area with
#   dead record versions + tombstones until the dead share exceeds ~30%.
#   The sweep's automatic pass SKIPS while the sweep checkpoint (CKP0) is
#   live (rollback truncates to absolute checkpoint positions) and runs
#   once it is realized: the area shrinks to exactly the live set, every
#   live file (incl. batched text members and a directory subtree) reads
#   bit-exact, fsck + verify --deep clean. INVFS_NO_COMPACT=1 suppresses
#   the automatic pass; --compact forces it alone; a read-only volume is
#   skipped with a message.
#
#   Leg A7 (rollback horizon): a second --compact right after a
#   successful one is a strict no-op ("area already compact"); a
#   checkpoint armed AFTER a compaction still rolls back bit-exact (its
#   absolute positions name the compacted area), post-checkpoint writes
#   vanish, fsck/verify clean.
#
#   Leg A8 (seal interplay): compaction under a LIVE seal proceeds (no
#   CKP0 can exist then -- vol_ckp_begin declines under a seal) and never
#   touches the \x01parity*-owned blocks: verify --deep reports zero
#   parity drift and the reseal is "0 stripes updated".
#
#   Leg B (--fast): a .tar is NOT decomposed, text is NOT batched -- every
#   RAW file takes only the generic per-segment recompress; a second
#   --fast run is a pure no-op; bit-exact, fsck/verify clean.
#
#   Leg C (crash legs, INVFS_COMPACT_ABORT_AT, the INVFS_RESIZE_ABORT_AT
#   pattern): kill -9 at "staged" (pre-arm: old area intact, the stranded
#   staging run is an fsck orphan), "armed", "copying" (a genuinely torn
#   area mid-copy) and "copied" -> the volume latches read-only +
#   needs-recovery, invf-sweep refuses, and invf-fsck -f rolls the staged
#   stream forward (idempotent) -> fsck clean, verify --deep clean,
#   bit-exact, area compacted.
#
# The engine harness is generated below and linked against the built
# engine objects (the test-flushfail.sh convention). Run from the repo
# root after `make` (or via tools/run-e2e.sh). Uses /dev/shm like the
# other soak scripts; image paths are RELATIVE (blkio treats /dev/* as
# raw devices).
set -e
set -o pipefail

REPO="${REPO:-$(cd "$(dirname "$0")/.." && pwd)}"
B=$REPO/bin
WORK=/dev/shm/wp22ecompact
IMG_A=wp22e-cm-a.img    # churn -> compact (+ ckp skip / realize / env off)
IMG_B=wp22e-cm-b.img    # --fast behaviour
IMG_C=wp22e-cm-c.img    # crash: staged
IMG_D=wp22e-cm-d.img    # crash: armed
IMG_E=wp22e-cm-e.img    # crash: copying (torn area)
IMG_F=wp22e-cm-f.img    # crash: copied
IMG_G=wp22e-cm-g.img    # compact twice + rollback-after-compact
IMG_H=wp22e-cm-h.img    # compaction under a live seal
rm -rf "$WORK" && mkdir -p "$WORK/orig" "$WORK/out"
cd /dev/shm
rm -f "$IMG_A" "$IMG_B" "$IMG_C" "$IMG_D" "$IMG_E" "$IMG_F" "$IMG_G" "$IMG_H"

fail() { echo "FAIL: $*" >&2; exit 1; }

